"""Render every preset in real PyMOL, with optional paired GPU and ray images."""

import argparse
import hashlib
import html
import json
from pathlib import Path
from time import perf_counter
from urllib.request import urlopen

import numpy as np
from PIL import Image, ImageDraw, ImageFont
from runtime import Viewer
from specimens import density, oxdna

from blender_style_in_pymol import __init_plugin__, blender_style
from blender_style_in_pymol.presets import (
    DENSITY_REPRESENTATIONS,
    MATERIALS,
    REPRESENTATIONS,
)

CASES = (*REPRESENTATIONS, *MATERIALS)
ATOMIC = {"spheres", "ball-and-stick", "sticks"}


def specimen(cmd, case, structure, output):
    blender_style("reset", name="all", _self=cmd)
    cmd.delete("all")
    if case in DENSITY_REPRESENTATIONS:
        source = density(cmd)
    elif case == "oxdna-ribbon":
        source = oxdna(cmd, output / "inputs")
    elif case in ATOMIC:
        cmd.fragment("trp", "sample")
        source = "PyMOL tryptophan fragment"
    else:
        cmd.load(str(structure), "sample")
        cmd.remove("sample and (solvent or hydro)")
        source = (
            "Crambin (PDB 1CRN)"
            if structure.stem.lower() == "1crn"
            else "User-supplied structure"
        )
    cmd.hide("everything")
    cmd.bg_color("white")
    cmd.set("opaque_background", 1)
    cmd.set("orthoscopic", 1)
    target = "density" if case in DENSITY_REPRESENTATIONS else "sample"
    if case in DENSITY_REPRESENTATIONS:
        cmd.reset()
    else:
        cmd.orient(target)
    cmd.turn("y", 20)
    cmd.turn("z", -15)
    cmd.zoom(target, 1 if case in DENSITY_REPRESENTATIONS else 4)
    cmd.clip("slab", 200)
    return source


def write_overview(output, rows, names, filename):
    selected = [row for row in rows if row["case"] in names]
    if not selected:
        return
    columns, width, height = 4, 360, 300
    canvas = Image.new(
        "RGB",
        (columns * width, ((len(selected) + columns - 1) // columns) * height),
        "white",
    )
    draw = ImageDraw.Draw(canvas)
    font = ImageFont.load_default(size=18)
    for index, row in enumerate(selected):
        x, y = (index % columns) * width, (index // columns) * height
        with Image.open(output / row["images"]["ray"]) as source:
            tile = source.convert("RGB")
            tile.thumbnail((width, height - 30), Image.Resampling.LANCZOS)
            canvas.paste(tile, (x + (width - tile.width) // 2, y))
        draw.text(
            (x + width // 2, y + height - 22),
            row["case"],
            fill="#253344",
            font=font,
            anchor="mm",
        )
    if selected:
        canvas.save(output / filename)


def validate(path, width, height):
    with Image.open(path) as image:
        pixels = np.asarray(image.convert("RGB"))
        if image.size != (width, height):
            raise ValueError(f"Unexpected image size: {path}")
    visible = int(np.count_nonzero(pixels.min(axis=2) < 235))
    if visible < 100:
        raise ValueError(f"Empty image: {path}")
    return {
        "visible_pixels": visible,
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
    }


def write_index(output, rows):
    cards = []
    for row in rows:
        pictures = "".join(
            f'<figure><img src="{html.escape(path)}" alt="{html.escape(row["case"])} {kind}" loading="lazy"><figcaption>{kind}</figcaption></figure>'
            for kind, path in row["images"].items()
        )
        cards.append(
            f"<article><h2>{html.escape(row['case'])}</h2><p>{html.escape(row['source'])}</p><div>{pictures}</div></article>"
        )
    page = """<!doctype html><html lang="en"><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Blender Style in PyMOL — Gallery</title><style>
body{font:16px system-ui;margin:2rem auto;max-width:1100px;padding:0 1rem;color:#253344;background:#f6f7f9}
h1{font-size:2rem}article{background:white;border:1px solid #dce0e6;border-radius:12px;padding:1rem;margin:1rem 0}
article div{display:flex;flex-wrap:wrap;gap:1rem}figure{flex:1;min-width:260px;margin:0}img{display:block;width:100%}
p,figcaption{color:#526075}h2{margin:.2rem 0}figcaption{text-align:center}
</style><h1>Blender Style in PyMOL</h1><p>Actual PyMOL renders of all molecular styles, density styles, oxDNA ribbon and legacy presets. Geometry and lighting are approximations of Molecular Nodes.</p><p><a href="https://github.com/th2ch-g/blender_style_in_pymol">Installation and documentation</a> · <a href="manifest.json">Render manifest</a></p>"""
    (output / "index.html").write_text(
        page + "".join(cards) + "</html>", encoding="utf-8"
    )
    markdown = [
        "# Blender Style in PyMOL — Gallery",
        "",
        "Generated by real PyMOL. [Source and documentation](https://github.com/th2ch-g/blender_style_in_pymol).",
        "",
        "| Representation / material | GPU | Ray |",
        "| --- | --- | --- |",
    ]
    for row in rows:
        pictures = [
            f"![{row['case']} {kind}]({row['images'][kind]})"
            if kind in row["images"]
            else "—"
            for kind in ("gpu", "ray")
        ]
        markdown.append(
            f"| `{row['case']}`<br>{row['source']} | {pictures[0]} | {pictures[1]} |"
        )
    (output / "README.md").write_text("\n".join(markdown) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--structure", type=Path, default=Path(".cache/reference/1crn.cif")
    )
    parser.add_argument("--fetch", action="store_true")
    parser.add_argument("--output", type=Path, default=Path(".cache/gallery"))
    parser.add_argument("--gui", action="store_true")
    parser.add_argument("--keep-open", action="store_true")
    parser.add_argument("--only", nargs="+", choices=CASES)
    parser.add_argument("--width", type=int, default=1200)
    parser.add_argument("--height", type=int, default=900)
    args = parser.parse_args()
    if args.fetch and not args.structure.exists():
        args.structure.parent.mkdir(parents=True, exist_ok=True)
        with urlopen(
            "https://files.rcsb.org/download/1CRN.cif", timeout=30
        ) as response:
            args.structure.write_bytes(response.read())
    if not args.structure.is_file():
        parser.error("Provide --structure or use --fetch to download 1CRN")
    args.output.mkdir(parents=True, exist_ok=True)
    viewer = Viewer(gui=args.gui)
    cmd = viewer.cmd
    __init_plugin__(_self=cmd)
    rows = []
    try:
        for case in args.only or CASES:
            print(f"Rendering {case}", flush=True)
            source = specimen(cmd, case, args.structure, args.output)
            representation = (
                "surface"
                if case in ("clay", "ambient-occlusion", "transparent")
                else None
            )
            entry = blender_style(
                case,
                representation=representation,
                quality="high",
                _self=cmd,
                quiet=1,
                params={"threshold": 0.2} if case in DENSITY_REPRESENTATIONS else None,
            )
            row = {
                "case": case,
                "source": source,
                "images": {},
                "stats": {},
                "preparation_seconds": entry["seconds"],
            }
            viewer.pump()
            for kind in ("gpu", "ray") if args.gui else ("ray",):
                path = args.output / f"{case}-{kind}.png"
                start = perf_counter()
                with viewer.context():
                    blender_style(
                        "png" if kind == "gpu" else "ray",
                        filename=path,
                        width=args.width,
                        height=args.height,
                        _self=cmd,
                    )
                row["images"][kind] = path.name
                row["stats"][kind] = {
                    **validate(path, args.width, args.height),
                    "seconds": perf_counter() - start,
                }
            rows.append(row)
            print(f"{case}: {', '.join(row['images'])}", flush=True)
        write_index(args.output, rows)
        write_overview(args.output, rows, REPRESENTATIONS, "representations.png")
        write_overview(args.output, rows, MATERIALS, "materials.png")
        (args.output / "manifest.json").write_text(
            json.dumps(
                {
                    "pymol": cmd.get_version()[0],
                    "width": args.width,
                    "height": args.height,
                    "cases": rows,
                },
                indent=2,
            )
        )
        if args.keep_open and args.gui:
            cmd.set("internal_gui", 1)
            cmd.set("internal_feedback", 1)
            blender_style("gui", _self=cmd)
            viewer.application.exec_()
    finally:
        viewer.close()


if __name__ == "__main__":
    main()
